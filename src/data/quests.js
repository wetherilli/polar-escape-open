//
// 이벤트에서 쓰는 법 (events.js의 c.quest)
//   c.quest.start('id')        시작 — 「새 퀘스트」 알림
//   c.quest.next('id')         다음 단계로 — 「퀘스트 갱신」 알림
//   c.quest.done('id')         완료 — 「퀘스트 완료」 알림
//   c.quest.stage('id')        지금 단계 번호 (시작 전 -1)
//   c.quest.started('id') / c.quest.active('id') / c.quest.finished('id')
// ─────────────────────────────────────────────

