// 대학원생의 도움 (전공 기믹) — 누가 무엇을 도와주는지는 작가가 정한다 (지금은 예시 하나)
//  퀘스트를 끝내거나 말을 걸었을 때 c.help.grant('id')로 준다. 한 번 받으면 계속 효과가 있고 세이브에 남는다.
//  메뉴 소지품 탭 「받은 도움」에 이름·설명이 나온다.
//
//  name     이름 (메뉴·알림)
//  from     도와준 사람 (메뉴에 표시)
//  desc     무엇이 좋아지는지 (메뉴에 표시)
//  effects  효과. 여러 개를 함께 줄 수 있고, 같은 효과를 여러 도움에서 받으면 곱해지거나(숫자) 합쳐진다(목록).
//    cold     냉동실험실 같은 추운 곳에서 체온이 줄어드는 빠르기 ×  (예: 0.5 = 절반 속도)
//    chase    추격자 속도 ×                                       (예: 0.8)
//    stamina  달릴 때 스태미나가 줄어드는 빠르기 ×                  (예: 0.7)
//    light    손전등 빛이 닿는 거리 ×                              (예: 1.3)
//    reveal   ['표시'] — 이벤트에 hiddenTag: '표시'를 달아 둔 숨은 요소가 보이게 된다
//    open     ['표시'] — maps.js의 helpDoor(…, '표시', …) 문이 열린다
//  아이템을 주는 도움은 효과 없이 장면에서 c.give('아이템')을 부르면 된다.
//
// 이벤트에서 쓰는 법 (events.js의 c.help)
//   c.help.grant('id')   도움 받기 — 「도움 — 이름」 알림. 이미 있으면 아무 일도 없다
//   c.help.has('id')     받았나
// ─────────────────────────────────────────────

export const HELPS = {
  // 예시 — 대학원생 A의 예시 퀘스트를 끝내면 받는다(npcs.js). 실제 도움을 정하면 지운다
  exampleHelp: {
    name: '(도움 예시 — 방한 요령)',
    from: '(대학원생 A)',
    desc: '(냉동실험실에서 체온이 절반 속도로 줄어든다 — 문구 미정)',
    effects: { cold: 0.5 },
  },
};
